const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const runtime=JSON.parse(fs.readFileSync(path.join(root,'原型/键位编辑器/data/structure-count-bindings.json'),'utf8'));
const runs=path.join(root,'数据/三模式/规则库/四键实验/键位试验');
const matches=fs.readdirSync(runs).filter(n=>n.endsWith('-'+runtime.version));
assert.equal(matches.length,1,'当前版本必须唯一对应报告');
const report=JSON.parse(fs.readFileSync(path.join(runs,matches[0],'大组结构键位分配.json'),'utf8'));
const manual=JSON.parse(fs.readFileSync(path.join(root,'数据/三模式/规则库/四键实验/人工审议.json'),'utf8'));
const policy=manual.ruleDecisions.find(r=>r.function==='family.closed_partition'&&r.decision==='accepted');
const BASE=(process.env.SHAPE_OVERVIEW_BASE_URL||'http://127.0.0.1:8765').replace(/\/$/,'');
const output = path.join(root, '原型/键位编辑器/测试输出/structure-count-bindings');
fs.mkdirSync(output, {recursive: true});
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    page.setDefaultTimeout(60000);
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => {if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`);});
    await page.goto(BASE + '/shape-key-overview.html#round=3');
    await page.waitForFunction(n => document.querySelector('#structureBindingStatus').textContent.includes(n.toLocaleString('zh-CN')), report.statistics.assigned);
    await page.waitForFunction(() => document.querySelector('#resultStatus').textContent.includes('1,554'));
    await page.click('[data-round="1"]');
    assert.equal(await page.locator('#structureRound1 [data-structure-key]').count(),10+Object.keys({...report.definitions.second,...(policy?.definitions||{})}).length);
    await page.click('#structureRound1 [data-structure-key="k"]');
    await page.waitForFunction(()=>document.querySelector('#keyInfo').textContent.includes('有孔拓扑'));
    await page.waitForFunction(()=>document.querySelector('#resultStatus').textContent.includes('3 个去重字符'));
    assert.equal(await page.locator('#results [data-cp="52"]').count(),1);
    assert.equal(await page.locator('#results [data-cp="68"]').count(),1);
    assert.equal(await page.locator('#results [data-cp="80"]').count(),1);
    await page.screenshot({path:path.join(output,'v4-有孔拓扑键.png'),fullPage:true});
    await page.click('#structureRound1 [data-structure-key="j"]');
    await page.waitForFunction(()=>document.querySelector('#keyInfo').textContent.includes('结构计数整字集合'));
    assert((await page.locator('#keyInfo').textContent()).includes('整字直连续笔集'));
    assert(await page.locator('#keyInfo [data-cp]').count()>0);
    await page.click('[data-round="2"]');
    assert.equal(await page.locator('#structureRound2 h3').count(),5);
    await page.locator('#structureRound2 [data-sample="J"]').click();
    await page.waitForFunction(()=>document.querySelector('#detail').textContent.includes('ajqu'));
    await page.click('[data-round="3"]');
    assert.equal(await page.locator('#structureRound3 details').first().locator('[data-prefix]').count(),report.statistics.newCodes);
    assert((await page.locator('#structureRound3').textContent()).includes('没有宣称旧大组已消除'));
    await page.click('[data-round="4"]');
    for(const [key,n] of [['assigned',report.statistics.assigned],['observationPending',report.statistics.observationPending],['scopePending',report.statistics.wholeScopePending],['withdrawn',report.scopeRevision.withdrawn.length],['reviewedRetained',report.statistics.reviewedRetained||0]]){
      await page.click(`[data-structure-queue="${key}"]`);
      await page.waitForFunction(n=>document.querySelector('#resultStatus').textContent.includes(`${n.toLocaleString('zh-CN')} 个去重字符`),n);
    }
    for (const width of [1440,768,390,320]) {
      await page.setViewportSize({width,height:1000});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    }
    await page.screenshot({path:path.join(output,'四轮同步-覆盖队列.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.click('[data-allocation="legacy"]');
    for(let n=1;n<=4;n++)assert(await page.locator('#structureRound'+n).isHidden());
    await page.click('[data-allocation="draft"]');
    await page.click('[data-round="3"]');
    await page.fill('#prefix', 'chjb');
    await page.click('#search button[type=submit]');
    await page.waitForFunction(n => document.querySelector('#resultStatus').textContent.includes(`${n} 个去重字符`),report.codeMembers.chjb.length);
    await page.fill('#prefix', '');
    await page.fill('#character', 'T');
    await page.click('#search button[type=submit]');
    await page.waitForFunction(() => document.querySelectorAll('#results .candidate').length === 1);
    await page.locator('#results .candidate').click();
    await page.waitForFunction(() => document.querySelector('#detail').textContent.includes('结构计数新入口'));
    assert((await page.locator('#detail').textContent()).includes('chjb'));
    assert((await page.locator('#detail').textContent()).includes('whole-glyph-collection:straightStrokes'));
    await page.click('[data-allocation="legacy"]');
    await page.waitForFunction(() => document.querySelector('#structureBindingStatus').textContent.includes('不启用'));
    await page.fill('#prefix', 'chjb');
    await page.fill('#character', '');
    await page.click('#search button[type=submit]');
    await page.waitForFunction(() => document.querySelector('#resultStatus').textContent.includes('0 个去重字符'));
    await page.click('[data-allocation="draft"]');
    await page.click('[data-round="1"]');
    await page.click('[data-position="3"]');
    await page.click('[data-key="j"]');
    await page.waitForFunction(() => document.querySelector('#keyInfo').textContent.includes('整字直连续笔集'));
    await page.screenshot({path: path.join(output, '总览新键.png'), fullPage: true});
    await page.goto(BASE + '/structure-count-review.html');
    await page.waitForFunction(() => document.querySelector('#count').textContent.includes('11061'));
    assert.equal(await page.locator('#group option').count(), 56);
    await page.selectOption('#group', 'chvc');
    assert((await page.locator('#comparison').textContent()).includes(`${report.groups.find(g=>g.code==='chvc').withBetterRoute} 字取得更小`));
    await page.selectOption('#status', 'pending');
    assert.equal(await page.locator('#count').textContent(), `${report.groups.find(g=>g.code==='chvc').pending} 个去重字符`);
    await page.click('#reset');
    await page.fill('#search', 'chjb');
    assert.equal(await page.locator('#count').textContent(), `${report.codeMembers.chjb.length} 个去重字符`);
    await page.fill('#search', 'ajqu');
    assert.equal(await page.locator('#count').textContent(), `${report.codeMembers.ajqu.length} 个去重字符`);
    const curveMembers=report.codeMembers.ajqu;
    for(const cp of [0x29,0x4a])assert(curveMembers.includes(cp));
    for(const cp of [0x66,0x6a,0x133])assert(!curveMembers.includes(cp));
    await page.fill('#search', 'f');
    assert((await page.locator('#grid').textContent()).includes('整字形族已人工确认'));
    assert.equal(await page.locator('#grid [data-code="ajqu"]').count(),0);
    await page.fill('#search', 'U+0054');
    assert.equal(await page.locator('#count').textContent(), '1 个去重字符');
    assert((await page.locator('#grid').textContent()).includes('chjb'));
    const glyph = page.locator('#grid .glyph').first();
    assert(await glyph.evaluate(async node => {
      const match = /url\(["']?(.*?)["']?\)/.exec(node.style.backgroundImage);
      const image = new Image(); image.src = match[1]; await image.decode(); return image.naturalWidth > 0;
    }));
    await page.click('#reset');
    await page.selectOption('#status', 'assigned');
    assert.equal(await page.locator('#count').textContent(), `${report.statistics.assigned} 个去重字符`);
    await page.click('#next');
    assert((await page.locator('#page').textContent()).startsWith('61'));
    for (const width of [1440, 768, 390, 320]) {
      await page.setViewportSize({width, height: 1000});
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`);
    }
    await page.setViewportSize({width: 1440, height: 1000});
    await page.screenshot({path: path.join(output, '大组新分配.png'), fullPage: true});
    await page.goto(BASE + '/structure-count-review.html?status=withdrawn&v=3');
    await page.waitForFunction(n => document.querySelector('#count').textContent===`${n} 个去重字符`,new Set([...report.scopeRevision.withdrawn.map(r=>r.cp),...report.records.filter(r=>r.withdrawnPWholeCodes?.length).map(r=>r.cp)]).size);
    assert((await page.locator('#grid').textContent()).includes('本轮退出：'));
    await page.screenshot({path:path.join(output,'其它前缀退出-v3.png'),fullPage:false});
    assert.deepEqual(errors, []);
    console.log('PASS public new codes, detail evidence, legacy isolation, keys, 55-group review, pending, pagination, sprites, 4 widths');
  } finally {await browser.close();}
})().catch(e => {console.error(e); process.exit(1);});
